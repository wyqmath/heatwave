class PathAwareRetriever:
    """Endpoint-Anchored Retrieval: checks EVERY option entity's connectivity
    to both start and end via KG.

    Unified strategy for 1/2/3/4-hop:
    - For each option entity e_i, check reachability to Start and End
    - Use single_source_shortest_path (2 BFS per question, not per entity)
    - Report direct edges with relationship labels (strong signal)
    - Report indirect paths ≤4 steps (weak signal)
    - Do NOT check internal edges between option entities
      (distractors from KG random walk have 100% internal connectivity,
       so internal edges provide zero discriminative signal)
    """

    def __init__(self, kg_G: nx.DiGraph, faiss_linker: FAISSLinker):
        self.kg = kg_G
        self.linker = faiss_linker
        self._undirected = kg_G.to_undirected()
        self._embed_rpm = RPMController(500)

    def _format_path_with_rels(self, path_nodes: list) -> str:
        """Format a path with relationship labels from the directed graph."""
        parts = []
        for i, node in enumerate(path_nodes):
            node_text = make_entity_readable(node)
            if i < len(path_nodes) - 1:
                u, v = node, path_nodes[i + 1]
                if self.kg.has_edge(u, v):
                    rel = self.kg[u][v].get("relationship", "related_to")
                    parts.append(f"{node_text} -[{rel}]->")
                elif self.kg.has_edge(v, u):
                    rel = self.kg[v][u].get("relationship", "related_to")
                    parts.append(f"{node_text} <-[{rel}]-")
                else:
                    parts.append(f"{node_text} -->")
            else:
                parts.append(node_text)
        return " ".join(parts)

    def _get_entity_evidence(self, entity_node: Optional[str], entity_text: str,
                             paths_from_start: dict, paths_from_end: dict,
                             start_text: str, end_text: str) -> Tuple[List[str], bool]:
        """Get KG evidence for one entity's connectivity to start and end."""
        lines = []
        has_evidence = False

        if entity_node is None:
            lines.append(f"    (not found in KG)")
            return lines, False

        # ── Connectivity to Start ──
        if entity_node in paths_from_start:
            path = paths_from_start[entity_node]
            path_len = len(path) - 1  # number of edges
            if path_len == 1:
                # Direct edge (strong signal)
                path_str = self._format_path_with_rels(path)
                lines.append(f"    ↔ Start: DIRECT ({path_str})")
            elif path_len <= 3:
                # Indirect path (weak signal)
                path_str = self._format_path_with_rels(path)
                lines.append(f"    ↔ Start: {path_len} steps ({path_str})")
            has_evidence = True
        else:
            lines.append(f"    ↔ Start: no path found in KG (>4 steps)")

        # ── Connectivity to End ──
        if paths_from_end is not None:
            if entity_node in paths_from_end:
                path = paths_from_end[entity_node]
                path_len = len(path) - 1
                # Reverse path direction for display (end→...→entity becomes entity→...→end)
                display_path = list(reversed(path))
                if path_len == 1:
                    path_str = self._format_path_with_rels(display_path)
                    lines.append(f"    ↔ End: DIRECT ({path_str})")
                elif path_len <= 3:
                    path_str = self._format_path_with_rels(display_path)
                    lines.append(f"    ↔ End: {path_len} steps ({path_str})")
                has_evidence = True
            else:
                lines.append(f"    ↔ End: no path found in KG (>4 steps)")

        return lines, has_evidence

    def get_context(self, question: dict) -> str:
        """Build endpoint-anchored evidence for all 4 options.

        Per question: 1-2 API calls (batch embed) + 2 BFS (single_source_shortest_path).
        """
        start = question["start_entity"]
        end = question.get("end_entity")
        hop = question["hop_count"]

        if hop == 1:
            end = None

        start_text = make_entity_readable(start)
        end_text = make_entity_readable(end) if end else ""

        # ── Batch embed all unique entities ──
        all_texts = [start_text]
        if end:
            all_texts.append(end_text)

        option_entity_map = []
        for opt in question["options"]:
            readable_entities = [make_entity_readable(e) for e in opt["entities"]]
            start_idx = len(all_texts)
            all_texts.extend(readable_entities)
            option_entity_map.append((start_idx, len(readable_entities), readable_entities))

        self._embed_rpm.acquire()
        all_linked = self.linker.link_batch(all_texts)

        s_node, _ = all_linked[0]
        if end:
            e_node, _ = all_linked[1]
        else:
            e_node = None

        # ── 2 BFS calls: paths from start and from end (cutoff=4) ──
        paths_from_start = {}
        if s_node and s_node in self._undirected:
            paths_from_start = nx.single_source_shortest_path(
                self._undirected, s_node, cutoff=4)

        paths_from_end = None
        if e_node and e_node in self._undirected:
            paths_from_end = nx.single_source_shortest_path(
                self._undirected, e_node, cutoff=4)

        # ── Build evidence for each option ──
        lines = []
        if end:
            lines.append(f"=== KG Evidence: {start_text} → ... → {end_text} ===")
        else:
            lines.append(f"=== KG Evidence: {start_text} → ? ===")
        lines.append("")

        for i, opt in enumerate(question["options"]):
            letter = opt["label"]
            opt_text = opt["text"]
            idx_start, count, readable_ents = option_entity_map[i]
            o_nodes = all_linked[idx_start: idx_start + count]

            lines.append(f"--- Option {letter}: {opt_text} ---")
            option_has_evidence = False

            for j, (entity_node_score, ent_text) in enumerate(zip(o_nodes, readable_ents)):
                entity_node, score = entity_node_score
                lines.append(f"  {ent_text}:")
                ent_lines, has_ev = self._get_entity_evidence(
                    entity_node, ent_text,
                    paths_from_start, paths_from_end,
                    start_text, end_text,
                )
                lines.extend(ent_lines)
                if has_ev:
                    option_has_evidence = True

            if not option_has_evidence:
                lines.append("  (no KG evidence found)")
            lines.append("")

        # ── Additional Context: start/end neighborhoods ──
        lines.append("--- Additional Context ---")
        if s_node and s_node in self.kg:
            for succ in list(self.kg.successors(s_node))[:5]:
                rel = self.kg[s_node][succ].get("relationship", "")
                lines.append(f"  {start_text} -[{rel}]-> {make_entity_readable(succ)}")
            for pred in list(self.kg.predecessors(s_node))[:3]:
                rel = self.kg[pred][s_node].get("relationship", "")
                lines.append(f"  {make_entity_readable(pred)} -[{rel}]-> {start_text}")

        if e_node and e_node in self.kg:
            for pred in list(self.kg.predecessors(e_node))[:5]:
                rel = self.kg[pred][e_node].get("relationship", "")
                lines.append(f"  {make_entity_readable(pred)} -[{rel}]-> {end_text}")
            for succ in list(self.kg.successors(e_node))[:3]:
                rel = self.kg[e_node][succ].get("relationship", "")
                lines.append(f"  {end_text} -[{rel}]-> {make_entity_readable(succ)}")

        return "\n".join(lines)


