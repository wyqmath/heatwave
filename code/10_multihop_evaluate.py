def load_merge_mapping() -> Dict[str, str]:
    if MERGE_MAPPING_JSON.exists():
        with open(MERGE_MAPPING_JSON, "r", encoding="utf-8") as f:
            return json.load(f)
    print("  WARNING: merge mapping not found")
