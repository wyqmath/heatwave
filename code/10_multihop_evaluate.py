def compute_metrics(records: List[dict]) -> dict:
    total = len(records)
    correct = sum(1 for r in records if r["correct"])
    failed = sum(1 for r in records if r["predicted"] == "X")
    valid = total - failed
    accuracy = correct / valid * 100 if valid > 0 else 0

    # Macro F1
    labels = ["A", "B", "C", "D"]
    f1_scores = []
    for label in labels:
        tp = sum(1 for r in records if r["predicted"] == label and r["expected"] == label)
        fp = sum(1 for r in records if r["predicted"] == label and r["expected"] != label)
        fn = sum(1 for r in records if r["expected"] == label and r["predicted"] != label)
        prec = tp / (tp + fp) if (tp + fp) > 0 else 0
        rec = tp / (tp + fn) if (tp + fn) > 0 else 0
        f1 = 2 * prec * rec / (prec + rec) if (prec + rec) > 0 else 0
        f1_scores.append(f1)
    macro_f1 = sum(f1_scores) / len(f1_scores)

    # Per-hop
    by_hop = defaultdict(list)
    for r in records:
        by_hop[r["hop_count"]].append(r)
    per_hop = {}
    for h in sorted(by_hop.keys()):
        hc = sum(1 for r in by_hop[h] if r["correct"])
        ht = len(by_hop[h])
        hf = sum(1 for r in by_hop[h] if r["predicted"] == "X")
        hv = ht - hf
        per_hop[str(h)] = {
            "total": ht, "correct": hc, "failed": hf,
            "accuracy": round(hc / hv * 100, 2) if hv > 0 else 0,
        }

    return {
        "total": total, "correct": correct, "failed": failed,
        "accuracy": round(accuracy, 2),
        "f1_macro": round(macro_f1, 4),
        "per_hop": per_hop,
    }


def bootstrap_ci(records: List[dict], n_bootstrap: int = 2000,
                 seed: int = 42) -> Tuple[float, float]:
    """95% Bootstrap CI for accuracy."""
    rng = np.random.RandomState(seed)
    n = len(records)
    accs = []
    for _ in range(n_bootstrap):
        sample = rng.choice(records, size=n, replace=True)
        valid = [r for r in sample if r["predicted"] != "X"]
        if valid:
            accs.append(sum(1 for r in valid if r["correct"]) / len(valid) * 100)
    return round(np.percentile(accs, 2.5), 2), round(np.percentile(accs, 97.5), 2)


def paired_delta_bootstrap(records_no_kg: List[dict], records_kg: List[dict],
                           n_bootstrap: int = 2000, seed: int = 42) -> Tuple[float, float, float]:
    """Paired bootstrap delta (KG - No-KG) with 95% CI."""
    # Align by id
    nokg_map = {r["id"]: r for r in records_no_kg}
    kg_map = {r["id"]: r for r in records_kg}
    common_ids = sorted(set(nokg_map.keys()) & set(kg_map.keys()))

    rng = np.random.RandomState(seed)
    deltas = []
    for _ in range(n_bootstrap):
        ids = rng.choice(common_ids, size=len(common_ids), replace=True)
        c_nokg = sum(1 for i in ids if nokg_map[i]["correct"])
        c_kg = sum(1 for i in ids if kg_map[i]["correct"])
        n = len(ids)
        deltas.append((c_kg - c_nokg) / n * 100)

    mean_delta = round(np.mean(deltas), 2)
    ci_lo = round(np.percentile(deltas, 2.5), 2)
    ci_hi = round(np.percentile(deltas, 97.5), 2)
    return mean_delta, ci_lo, ci_hi


def mcnemar_test(records_no_kg: List[dict], records_kg: List[dict]) -> float:
    """McNemar's test p-value."""
    from scipy import stats as scipy_stats

    nokg_map = {r["id"]: r["correct"] for r in records_no_kg}
    kg_map = {r["id"]: r["correct"] for r in records_kg}
    common_ids = sorted(set(nokg_map.keys()) & set(kg_map.keys()))

    # b = no_kg correct, kg wrong; c = no_kg wrong, kg correct
    b = sum(1 for i in common_ids if nokg_map[i] and not kg_map[i])
    c = sum(1 for i in common_ids if not nokg_map[i] and kg_map[i])

    if b + c == 0:
        return 1.0

    # McNemar with continuity correction
    chi2 = (abs(b - c) - 1) ** 2 / (b + c)
    p_value = 1 - scipy_stats.chi2.cdf(chi2, df=1)
    return p_value


