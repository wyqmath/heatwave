class FAISSLinker:
    """FAISS-based entity linker using merged centroid embeddings."""

    def __init__(self, kg_graph: nx.DiGraph, merge_map: Dict[str, str],
                 threshold: float = 0.82):
        import faiss as _faiss
        self.faiss = _faiss
        self.threshold = threshold
        self._build_merged_index(kg_graph, merge_map)

        import requests as _requests
        self._requests = _requests

    def _build_merged_index(self, kg_graph: nx.DiGraph, merge_map: Dict[str, str]):
        entities_path = ENTITY_EMBED_DIR / "entities.json"
        embeddings_path = ENTITY_EMBED_DIR / "embeddings.npy"

        with open(entities_path, "r", encoding="utf-8") as f:
            orig_data = json.load(f)
        orig_entities = orig_data["entities"]
        orig_embeddings = np.load(str(embeddings_path)).astype("float32")

        entity_to_idx = {e: i for i, e in enumerate(orig_entities)}

        # Group by canonical name
        canonical_groups: Dict[str, List[int]] = {}
        for e in orig_entities:
            canon = merge_map.get(e, e)
            if canon not in canonical_groups:
                canonical_groups[canon] = []
            canonical_groups[canon].append(entity_to_idx[e])

        # Only keep KG nodes
        kg_node_set = set(kg_graph.nodes())
        self.nodes: List[str] = []
        centroids_list = []

        for canon, indices in sorted(canonical_groups.items()):
            if canon not in kg_node_set:
                continue
            group_vecs = orig_embeddings[indices]
            centroid = group_vecs.mean(axis=0)
            self.nodes.append(canon)
            centroids_list.append(centroid)

        centroids = np.array(centroids_list, dtype="float32")
        self.faiss.normalize_L2(centroids)
        self.index = self.faiss.IndexFlatIP(centroids.shape[1])
        self.index.add(centroids)
        self._node_set = set(self.nodes)

        print(f"  FAISS index: {self.index.ntotal} merged entities (threshold={self.threshold})")

    def _get_embedding(self, text: str) -> np.ndarray:
        headers = {"Authorization": f"Bearer {EMBED_API_KEY}",
                   "Content-Type": "application/json"}
        payload = {"model": EMBED_MODEL, "input": [text], "encoding_format": "float"}
        try:
            resp = self._requests.post(EMBED_API_URL, headers=headers,
                                       json=payload, timeout=15)
            if resp.status_code == 200:
                return np.array(resp.json()["data"][0]["embedding"], dtype=np.float32)
        except Exception:
            pass
        return np.zeros(1024, dtype=np.float32)

    def _get_embeddings_batch(self, texts: List[str]) -> List[np.ndarray]:
        """Batch embed multiple texts. DashScope allows max 10 per call."""
        if not texts:
            return []
        BATCH_MAX = 10
        all_embeddings = []
        for i in range(0, len(texts), BATCH_MAX):
            chunk = texts[i:i + BATCH_MAX]
            headers = {"Authorization": f"Bearer {EMBED_API_KEY}",
                       "Content-Type": "application/json"}
            payload = {"model": EMBED_MODEL, "input": chunk, "encoding_format": "float"}
            try:
                resp = self._requests.post(EMBED_API_URL, headers=headers,
                                           json=payload, timeout=30)
                if resp.status_code == 200:
                    data = resp.json()["data"]
                    sorted_data = sorted(data, key=lambda x: x["index"])
                    all_embeddings.extend([np.array(d["embedding"], dtype=np.float32) for d in sorted_data])
                else:
                    all_embeddings.extend([np.zeros(1024, dtype=np.float32) for _ in chunk])
            except Exception:
                all_embeddings.extend([np.zeros(1024, dtype=np.float32) for _ in chunk])
        return all_embeddings

    def link(self, text: str) -> Tuple[Optional[str], float]:
        """Link natural language text to KG node.
        Returns (node_name, score) or (None, score) if below threshold.
        """
        vec = self._get_embedding(text).reshape(1, -1)
        self.faiss.normalize_L2(vec)
        scores, idxs = self.index.search(vec, 1)
        idx = idxs[0][0]
        score = float(scores[0][0])
        if idx >= 0 and idx < len(self.nodes) and score >= self.threshold:
            return self.nodes[idx], score
        return None, score

    def link_batch(self, texts: List[str]) -> List[Tuple[Optional[str], float]]:
        """Batch link: 1 API call for all texts, then per-text FAISS search.
        Reduces API calls from N to 1 per question.
        """
        embeddings = self._get_embeddings_batch(texts)
        results = []
        for vec in embeddings:
            vec = vec.reshape(1, -1)
            self.faiss.normalize_L2(vec)
            scores, idxs = self.index.search(vec, 1)
            idx = idxs[0][0]
            score = float(scores[0][0])
            if idx >= 0 and idx < len(self.nodes) and score >= self.threshold:
                results.append((self.nodes[idx], score))
            else:
                results.append((None, score))
        return results


