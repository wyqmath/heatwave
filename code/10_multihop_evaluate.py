# Evaluation Loop (with checkpoint/resume)
# ============================================================

def evaluate(
    model_name: str,
    questions: List[dict],
    llm: LLMClient,
    retriever: Optional[PathAwareRetriever],
    mode: str,  # "no_kg" or "plus_kg"
    output_jsonl: Path,
) -> List[dict]:
    """Run evaluation with JSONL checkpoint/resume."""
    # Load existing results for resume
    done_ids = set()
    if output_jsonl.exists():
        with open(output_jsonl, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    rec = json.loads(line)
                    done_ids.add(rec["id"])
        print(f"  Resuming: {len(done_ids)} already done, {len(questions) - len(done_ids)} remaining")

    todo = [q for q in questions if q["id"] not in done_ids]
    if not todo:
        print(f"  All {len(questions)} questions already completed!")
        # Load all results
        results = []
        with open(output_jsonl, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    results.append(json.loads(line))
        return results

    use_kg = (mode == "plus_kg")
    correct_count = sum(1 for _ in [])  # will count below
    file_lock = threading.Lock()

    # Load existing results into memory
    results = []
    if done_ids:
        with open(output_jsonl, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    results.append(json.loads(line))
        correct_count = sum(1 for r in results if r.get("correct"))

    def process_one(q: dict) -> dict:
        # Build question text with options
        opts_lines = []
        for opt in q["options"]:
            opts_lines.append(f"{opt['label']}. {opt['text']}")
        q_with_opts = q["question"] + "\n" + "\n".join(opts_lines)

        if use_kg and retriever:
            ctx = retriever.get_context(q)
            prompt = PROMPT_PLUS_KG.format(
                evidence_block=ctx,
                question_with_options=q_with_opts,
            )
        else:
            prompt = PROMPT_NO_KG.format(question_with_options=q_with_opts)

        raw = llm.call([{"role": "user", "content": prompt}])
        predicted = parse_answer(raw)

        rec = {
            "id": q["id"],
            "hop_count": q["hop_count"],
            "predicted": predicted,
            "expected": q["answer"],
            "correct": predicted == q["answer"],
            "raw_response": raw[:50],
        }

        # Append to JSONL (thread-safe)
        with file_lock:
            with open(output_jsonl, "a", encoding="utf-8") as f:
                f.write(json.dumps(rec, ensure_ascii=False) + "\n")

        return rec

    desc = f"{model_name} ({mode})"
    with ThreadPoolExecutor(max_workers=6) as pool:
        futures = {pool.submit(process_one, q): q["id"] for q in todo}
        pbar = tqdm(total=len(todo), desc=desc, ncols=90)
        for fut in as_completed(futures):
            rec = fut.result()
            results.append(rec)
            if rec["correct"]:
                correct_count += 1
            total_done = len(results)
            pbar.set_postfix(acc=f"{correct_count}/{total_done}")
            pbar.update(1)
        pbar.close()

    return results


