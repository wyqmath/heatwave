class RPMController:
    """Per-base_url sliding-window rate limiter."""
    def __init__(self, rpm: int = 200):
        self.rpm = rpm
        self._times: deque = deque()
        self._lock = threading.Lock()

    def acquire(self):
        with self._lock:
            now = time.time()
            while self._times and self._times[0] < now - 60:
                self._times.popleft()
            if len(self._times) >= self.rpm:
                wait = 60 - (now - self._times[0]) + 0.05
                if wait > 0:
                    time.sleep(wait)
            self._times.append(time.time())


class LLMClient:
    def __init__(self, cfg: dict, rpm_ctrl: RPMController):
        self.client = OpenAI(api_key=cfg["api_key"], base_url=cfg["base_url"])
        self.model = cfg["model"]
        self.rpm = rpm_ctrl
    def call(self, messages: list, max_tokens: int = 10,
             temperature: float = 0.0) -> str:
        for attempt in range(5):
            try:
                self.rpm.acquire()
                kwargs = dict(
                    model=self.model,
                    messages=messages,
                    max_tokens=max_tokens,
                    temperature=temperature,
                    timeout=60,
                )
                resp = self.client.chat.completions.create(**kwargs)
                content = resp.choices[0].message.content
                if content is None:
                    content = getattr(resp.choices[0].message, "reasoning_content", "")
                return (content or "").strip()
            except Exception as e:
                wait = min(2 ** attempt + random.random(), 30)
                print(f"  [retry {attempt+1}/5] {type(e).__name__}: {e} → sleep {wait:.1f}s")
                time.sleep(wait)
        return ""


def make_entity_readable(name: str) -> str:
    readable = re.sub(r'(?<=[a-z])(?=[A-Z])', ' ', name)
    readable = re.sub(r'(?<=[A-Z])(?=[A-Z][a-z])', ' ', readable)
    return readable


def parse_answer(text: str) -> str:
    text = text.strip().upper()
    for c in ["A", "B", "C", "D"]:
        if c in text:
            return c
    return "X"


